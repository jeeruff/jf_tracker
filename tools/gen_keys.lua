-- tools/gen_keys.lua (6 ноя) — раздел «All keys» мануала из keyhelp: один источник клавиш.
-- lua tools/gen_keys.lua        — переписать раздел в jf_tracker_help.html (между <!-- keys:begin --> и <!-- keys:end -->)
-- lua tools/gen_keys.lua check  — только сравнить (tests/test_keys_sync.lua): 0 — совпадает
-- Клавиши правятся в jf_tracker_keyhelp.lua; html после правки — этим скриптом, руками раздел не трогать.
local DIR = (arg and arg[0] or ''):match('(.*)/tools/') or '.'
local KH = dofile(DIR .. '/jf_tracker_keyhelp.lua')

local function esc(s) return (tostring(s or ''):gsub('&', '&amp;'):gsub('<', '&lt;'):gsub('>', '&gt;')) end
local function kbd(k)
  -- «dd yy p» → <kbd>dd</kbd> <kbd>yy</kbd> <kbd>p</kbd>; длинные подписи (слова) — <code>
  local out = {}
  for t in tostring(k):gmatch('%S+') do
    if #t <= 12 then out[#out + 1] = '<kbd>' .. esc(t) .. '</kbd>' else out[#out + 1] = '<code>' .. esc(t) .. '</code>' end
  end
  return table.concat(out, ' ')
end

local function build()
  local L = { '<!-- keys:begin (generated by tools/gen_keys.lua from jf_tracker_keyhelp.lua - do not edit by hand) -->',
    '<h2 id="keys">All keys</h2>',
    '<p>Every key of every module, as the <kbd>?</kbd> pane shows it. Generated from one list, so it never lags behind the tracker.</p>' }
  local seen = {}
  local order = {}
  for _, p in ipairs(KH.ORDER or {}) do if KH.PAGES[p] then order[#order + 1] = p; seen[p] = true end end
  local rest = {}
  for p in pairs(KH.PAGES) do if not seen[p] then rest[#rest + 1] = p end end
  table.sort(rest)
  for _, p in ipairs(rest) do order[#order + 1] = p end
  for _, p in ipairs(order) do
    local pg = KH.PAGES[p]
    if pg.e and #pg.e > 0 then
      L[#L + 1] = ('<h3 id="keys-%s">%s</h3>'):format(esc(p), esc(pg.title or p))
      L[#L + 1] = '<table>'
      for _, e in ipairs(pg.e) do
        if type(e) == 'table' and e.k then
          L[#L + 1] = ('<tr><td>%s</td><td>%s</td></tr>'):format(kbd(e.k), esc(e.d or e.m or ''))
        end
      end
      L[#L + 1] = '</table>'
    end
  end
  L[#L + 1] = '<!-- keys:end -->'
  return table.concat(L, '\n')
end

local path = DIR .. '/jf_tracker_help.html'
local f = assert(io.open(path, 'r')); local html = f:read('a'); f:close()
local block = build()
local a, b = html:find('<!%-%- keys:begin.-<!%-%- keys:end %-%->')
local new
if a then new = html:sub(1, a - 1) .. block .. html:sub(b + 1)
else
  local at = html:find('<h2 id="map">', 1, true) or html:find('</body>', 1, true) or (#html + 1)
  new = html:sub(1, at - 1) .. block .. '\n\n' .. html:sub(at)
end
if arg[1] == 'check' then
  if new ~= html then print('jf_tracker_help.html: All keys is out of date - run lua tools/gen_keys.lua'); os.exit(1) end
  os.exit(0)
end
if new ~= html then local w = assert(io.open(path, 'w')); w:write(new); w:close(); print('All keys written') else print('All keys up to date') end
