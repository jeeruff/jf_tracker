-- test_tour.lua — тур tutorial на стабах: шаги засчитываются действием
package.path = './?.lua;' .. package.path
_G.gfx = { mouse_x = 0, mouse_y = 0, rect = function() end }
local T = dofile('jf_tracker_tour.lua')
local n, bad = 0, 0
local function eq(name, got, want) n = n + 1; if got ~= want then bad = bad + 1; print(('FAIL %s: got %s, want %s'):format(name, tostring(got), tostring(want))) end end
local env = { fi = 1, row = 0, mode = 'normal', inst = 1, change = 0, hj = 0 }
local function e(t) local x = {}; for k, v in pairs(env) do x[k] = v end; for k, v in pairs(t or {}) do x[k] = v end; return x end
T.start(); eq('start asks for the tracker focus', T.want_focus, 'tracker')
-- 2 ноя: шаг 1 — пустая вкладка, tt создаёт трек
T.tick(e({ ntr = 0 }), -3); eq('clean: waits for tt', T.ok, false)
T.tick(e({ ntr = 1 }), -2.5); eq('clean: tt -> ok', T.ok, true)
T.tick(e({ ntr = 1 }), -1); eq('clean -> step 2', T.step, 2)
T.tick(e(), 0)
eq('step 2 (why jf) waits', T.ok, false)
T.tick(e({ row = 1 }), 1); eq('j -> ok', T.ok, true)
T.tick(e({ row = 1 }), 2); eq('advances to step 3 (move)', T.step, 3)
T.tick(e({ row = 1 }), 2.1)
T.tick(e({ row = 2 }), 2.2); eq('move: j alone not enough, h/l needed', T.ok, false)
T.tick(e({ row = 2, fi = 2 }), 3); eq('l alone - first item only', T.ok, false)
T.tick(e({ row = 2, fi = 1 }), 3.5); eq('l then h -> ok', T.ok, true)
T.tick(e({ row = 2, fi = 1 }), 4.4); eq('step 4 (f)', T.step, 4)
T.tick(e({ row = 2, fi = 2 }), 4.5)
T.tick(e({ row = 2, fi = 2, hints = true }), 4.8)
T.tick(e({ row = 2, fi = 2, hj = 1 }), 5); eq('labels shown, then a jump -> ok', T.ok, true)
T.tick(e({ row = 2, fi = 2, hj = 1 }), 6); eq('step 5 (panes)', T.step, 5)
T.tick(e({ row = 2, fi = 2, hj = 1, tk = 'a', focus = 'tracker', ntr = 1 }), 6.1)
T.tick(e({ hj = 1, tk = 'b', focus = 'tracker', ntr = 2 }), 6.15); eq('tt: second track, cursor moved - not yet', T.ok, false)
T.tick(e({ row = 2, fi = 3, hj = 1, tk = 'a', focus = 'tracker', ntr = 2 }), 6.2); eq('Opt+H alone not yet', T.ok, false)
T.tick(e({ tk = 'a', focus = 'inst', hj = 1, ntr = 2 }), 6.3)
T.tick(e({ tk = 'a', focus = 'tracker', hj = 1, ntr = 2 }), 6.4); eq('track, pane, back -> ok', T.ok, true)
T.tick(e({ tk = 'a', focus = 'tracker', hj = 1, ntr = 2 }), 7.3); eq('step 6 (modes)', T.step, 6)
T.tick(e({ row = 2, fi = 2, hj = 1 }), 7.4)
T.tick(e({ mode = 'insert', hj = 1 }), 7); eq('insert alone not yet', T.ok, false)
T.tick(e({ mode = 'normal', hj = 1 }), 8); eq('insert then Esc -> ok', T.ok, true)
T.go(1); eq('step 7 (write notes) stays in the tracker', T.want_focus, 'tracker')
T.go(1); eq('step 8 asks for the lib focus', T.want_focus, 'inst')
T.go(-7); eq('back to step 1', T.step, 1); eq('step reset', T.ok, false)
T.go(5); eq('forward', T.step, 6)
-- 2 ноя: назад на шаг, уже выполненный в первом кадре, — остаётся на нём (раньше сам уходил вперёд)
T.go(3); T.tick(e({ change = 5 }), 20); T.tick(e({ change = 6 }), 20.5); eq('slice: an edit -> ok', T.ok, true)
T.go(-1); T.go(1); T.tick(e({ change = 6, focus = 'tracker' }), 21); eq('back to slice: waits again', T.ok, false)
T.go(50); eq('forward clamps', T.step, #T.STEPS)
T.stop(); eq('stopped', T.active, false)
eq('16 steps (2 ноя: + clean, panes)', #T.STEPS, 16)
print(('%d checks, %d failed'):format(n, bad))
os.exit(bad == 0 and 0 or 1)
